"""Publish aggregate hybrid validation without rerunning inference."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def publish() -> None:
    """Preserve existing model comparisons and feature ablations."""
    report = json.loads(
        (ROOT / "backend/models/m5_validation_002/validation_metrics.json").read_text()
    )
    prior = json.loads(
        (ROOT / "backend/models/m5_validation_001/validation_metrics.json").read_text()
    )
    (ROOT / "docs/HYBRID_RESULTS.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    lines = [
        "# Preliminary rules and hybrid validation",
        "",
        "Generated by `python -m ml.report_hybrid`; validation only, human-unverified data.",
        "",
        "| System | Macro-F1 | Scam recall |",
        "|---|---:|---:|",
    ]
    lines += [
        f"| {r['name']} | {r['macro_f1']:.4f} | {r['per_class']['scam']['r']:.4f} |"
        for r in report["rows"]
    ]
    old = next(r["macro_f1"] for r in prior["rows"] if r["name"] == "hybrid")
    lines += [
        "",
        "## Fix cycle and interpretation",
        "",
        f"Initial hybrid macro-F1 was {old:.4f}. Abuse-driven high risk with an incidental scam cue caused two label overrides. Requiring the scam axis to be at least as strong as the abuse axis removes these errors.",
        "Hybrid now matches ML-only on this validation mixture; no improvement over ML is claimed. Rules-only has limited coverage.",
        "Risk uses max(scam axis, abuse axis). Rule IDs are R01-R11; flagged language is masked. R05 requires request context and excludes clause-local safety negation. These are lexical heuristics, not general negation understanding.",
        "Without a trained URL probability, use the no-URL fusion and explicitly explain the missing URL model. Credential request plus URL retains its configured risk floor.",
        report["policy_note"],
        "The sweep measures harmful-vs-normal detection, not alert severity. High-risk alert calibration remains pending. Explanations currently include rule descriptions and leading model class; n-gram attribution remains pending.",
        "No test/custom hold-out predictions, public message examples, or new trained artifacts were saved.",
        "",
        "## Reproduction",
        "",
        "From backend: `python -m ml.evaluate_hybrid --output models/<fresh-run-directory>`; output must not exist. Frozen partitions are verified. Completed runs must not be repeated just to publish.",
        "`python -m ml.report_hybrid` publishes the completed run and preserves feature ablations.",
    ]
    (ROOT / "docs/RULES_RISK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    path = ROOT / "backend/models/metrics.json"
    metrics = json.loads(path.read_text())
    name = "ml_rules_hybrid"
    metrics["ablations"] = [
        a for a in metrics.get("ablations", []) if a["name"] != name
    ] + [{"name": name, "rows": report["rows"]}]
    path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")


if __name__ == "__main__":
    publish()
    print("Aggregate hybrid report published.")
