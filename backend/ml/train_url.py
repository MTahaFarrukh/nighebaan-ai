"""Train static URL models on frozen train/validation only, never test."""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path

import joblib
import pandas as pd
from app.services.url_transformer import URLFeatureTransformer
from ml.url_data import ROOT, prepare
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler


def train(output: Path) -> None:
    """Compare fixed LR/RF/GB candidates; promote validation winner without refitting."""
    target = ROOT / "backend/models/url_clf.joblib"
    if output.exists() or target.exists():
        raise ValueError("Output or promoted model already exists.")
    splits, manifest = prepare()
    transformer = URLFeatureTransformer()
    X_train = transformer.transform(splits["train"].URL)
    X_val = transformer.transform(splits["val"].URL)
    y_train, y_val = splits["train"].label, splits["val"].label
    candidates = {
        "url_lr": Pipeline(
            [
                ("scale", StandardScaler()),
                (
                    "classifier",
                    LogisticRegression(
                        max_iter=1000, class_weight="balanced", random_state=42
                    ),
                ),
            ]
        ),
        "url_rf": RandomForestClassifier(
            n_estimators=150,
            max_depth=18,
            min_samples_leaf=3,
            class_weight="balanced",
            random_state=42,
            n_jobs=2,
        ),
        "url_gb": HistGradientBoostingClassifier(
            max_iter=150, max_leaf_nodes=31, class_weight="balanced", random_state=42
        ),
    }
    rows, best_score, best = [], -1.0, None
    output.mkdir(parents=True)
    for name, model in candidates.items():
        print(f"Training {name}", flush=True)
        model.fit(X_train, y_train)
        predicted = model.predict(X_val)
        detail = classification_report(
            y_val,
            predicted,
            labels=[0, 1],
            target_names=["benign", "phishing"],
            output_dict=True,
            zero_division=0,
        )
        row = {
            "name": name,
            "macro_f1": float(f1_score(y_val, predicted, average="macro")),
            "accuracy": float(accuracy_score(y_val, predicted)),
            "per_class": {
                key: {
                    "p": detail[key]["precision"],
                    "r": detail[key]["recall"],
                    "f1": detail[key]["f1-score"],
                }
                for key in ["benign", "phishing"]
            },
            "confusion_matrix": confusion_matrix(
                y_val, predicted, labels=[0, 1]
            ).tolist(),
        }
        rows.append(row)
        print(json.dumps(row), flush=True)
        if row["macro_f1"] > best_score:
            best_score, best, best_name = row["macro_f1"], model, name
    pipeline = Pipeline([("features", transformer), ("classifier", best)])
    joblib.dump(pipeline, target)
    fingerprint = hashlib.sha256(target.read_bytes()).hexdigest()
    artifact_manifest = {
        "sha256": fingerprint,
        "best_model": best_name,
        "classes": [0, 1],
        "evaluation_split": "validation",
        "feature_code_sha256": hashlib.sha256(
            (ROOT / "backend/app/services/url_features.py").read_bytes()
        ).hexdigest(),
    }
    target.with_suffix(".manifest.json").write_text(
        json.dumps(artifact_manifest, indent=2), encoding="utf-8"
    )
    result = {
        "generated_at": datetime.now(UTC).isoformat(),
        "evaluation_split": "validation",
        "test_evaluated": False,
        "dataset": manifest,
        "models": rows,
        "best_model": best_name,
        "policy": "Fixed candidates; selection by validation macro-F1; no test predictions.",
        "limitations": "Random URL split may share hosts across partitions; lexical-only and source-specific evaluation is not real-world safety assurance.",
    }
    (output / "metrics.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    (ROOT / "docs/URL_MODEL_RESULTS.json").write_text(
        json.dumps(result, indent=2), encoding="utf-8"
    )
    lines = [
        "# Static URL model validation",
        "",
        "Generated by `python -m ml.train_url`. Source: [UCI PhiUSIIL](https://archive.ics.uci.edu/dataset/967/phiusiil%2Bphishing%2Burl%2Bdataset), CC BY 4.0, Prasad & Chandra (2024).",
        "",
        "| Model | Validation macro-F1 | Phishing recall |",
        "|---|---:|---:|",
    ]
    lines += [
        f"| {r['name']} | {r['macro_f1']:.4f} | {r['per_class']['phishing']['r']:.4f} |"
        for r in rows
    ]
    lines += [
        "",
        f"Selected: {best_name}.",
        result["policy"],
        result["limitations"],
        f"Validation rows sharing training hostnames: {manifest['validation_rows_with_training_hostname']}.",
        "Source labels inverted explicitly: 0 phishing -> 1; 1 legitimate -> 0. Only raw URL and labels read. URL strings stay in memory; models store numeric features only.",
        "Canonical URL deduplication and contradictory-label removal precede stratified 70/15/15 splitting, seed 42. Test predictions remain untouched.",
        "Subdomain count is an approximate dot count, not a public-suffix lookup. No submitted URL is fetched, resolved or visited.",
        "Reproduce from backend: `python -m ml.train_url --output models/<fresh-run>` in a checkout without an existing promoted URL artifact. Source hash and split fingerprints must match the saved inventory. Do not rerun completed training.",
    ]
    (ROOT / "docs/URL_MODEL.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    record_experiments(result, output.name)
    active = ROOT / "backend/models/metrics.json"
    metrics = json.loads(active.read_text())
    metrics["url_models"] = rows
    metrics["best_url_model"] = best_name
    active.write_text(json.dumps(metrics, indent=2), encoding="utf-8")


def record_experiments(result: dict, run_id: str) -> None:
    """Append idempotent aggregate experiment records without source URL data."""
    path = ROOT / "backend/models/experiments.csv"
    existing = (
        pd.read_csv(path, keep_default_na=False) if path.exists() else pd.DataFrame()
    )
    entries = pd.DataFrame(
        [
            {
                "run_id": run_id,
                "timestamp": result["generated_at"],
                "model": row["name"],
                "variant": row["name"],
                "params": "fixed static URL candidates; ml/train_url.py",
                "val_macro_f1": row["macro_f1"],
                "evaluation_split": "validation",
            }
            for row in result["models"]
        ]
    )
    pd.concat([existing, entries], ignore_index=True).drop_duplicates(
        ["run_id", "variant"], keep="last"
    ).to_csv(path, index=False)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        train(args.output)
    except (OSError, ValueError, KeyError, TypeError, RuntimeError):
        parser.exit(1, "URL training failed; no source URLs logged.\n")
