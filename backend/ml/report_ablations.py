"""Publish aggregate ablation evidence without rerunning models or exposing text."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]


def publish(run: Path) -> None:
    """Export reproducible tables and append run-keyed aggregate experiment rows."""
    metrics = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
    rows = metrics["ablations"][0]["rows"]
    report = {
        "evaluation_split": "validation",
        "data_review_status": metrics["data_review_status"],
        "test_evaluated": False,
        "notes": metrics["ablation_notes"],
        "rows": rows,
    }
    (ROOT / "docs/ABLATION_RESULTS.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    lines = [
        "# Controlled preliminary LR ablations",
        "",
        "Generated by `python -m ml.report_ablations`. Same frozen validation population,",
        "balanced LR with C=2 selected previously on training CV; no per-variant tuning.",
        "Public text and temporary models stayed in memory. No test/hold-out predictions.",
        "",
        "| Variant | Training rows | Validation macro-F1 | Scam recall |",
        "|---|---:|---:|---:|",
    ]
    lines += [
        f"| {row['name']} | {row['train_rows']} | {row['macro_f1']:.4f} | {row['per_class']['scam']['r']:.4f} |"
        for row in rows
    ]
    lines += [
        "",
        "## Interpretation and limits",
        "",
        "- Combined word/char features outperform either view alone in this fixed-LR experiment.",
        "- Stopword removal slightly lowers validation macro-F1; keep the default disabled.",
        "- Removing SMS from training substantially lowers performance on the unchanged validation mixture, which still includes SMS. This does not establish Roman Urdu scam performance on its own.",
        "- Raw original text slightly outperforms the fully normalized variant here. Do not claim the complete normalization pipeline improves this validation score. The difference has no significance interval.",
        "- Lexical normalization alone yields a small gain relative to disabling only the map, with entity cleaning held constant.",
        "- Original text is recovered by (source, normalized text) keys; first matching original is retained for same-source duplicates. Deduplication and membership remain defined by the frozen normalized corpus.",
        "- Raw-text vocabularies/models are never serialized. No public examples are exported.",
        "- The promoted LR/SVM ensemble is unchanged. These are LR ablations, not re-tuned ensemble comparisons.",
        "- Rules-only/ML-only/hybrid ablation and validation error-analysis/fix cycle remain M5 work.",
        "",
        "## Reproduction",
        "",
        "From backend: `.venv/Scripts/python.exe -u -m ml.evaluate --output models/ablations_preliminary_001`.",
        "Completed aggregate checkpoints resume when fingerprints match. Do not edit runner/loader during a run.",
        "`--variant` can select individual variants; avoid using partial-run output as a complete table.",
        "Export: `.venv/Scripts/python.exe -m ml.report_ablations`.",
        "Current data remains preliminary/human-unverified; final test evaluation is still pending.",
    ]
    (ROOT / "docs/ABLATIONS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    active_path = ROOT / "backend/models/metrics.json"
    active = json.loads(active_path.read_text(encoding="utf-8"))
    names = {item["name"] for item in metrics["ablations"]}
    active["ablations"] = [
        item for item in active.get("ablations", []) if item["name"] not in names
    ] + metrics["ablations"]
    active["ablation_notes"] = metrics["ablation_notes"]
    active_path.write_text(json.dumps(active, indent=2), encoding="utf-8")
    log_path = ROOT / "backend/models/experiments.csv"
    existing = (
        pd.read_csv(log_path, keep_default_na=False)
        if log_path.exists()
        else pd.DataFrame()
    )
    entries = pd.DataFrame(
        [
            {
                "run_id": run.name,
                "timestamp": metrics["generated_at"],
                "model": "lr",
                "variant": row["name"],
                "params": json.dumps({"C": row["C"], "class_weight": "balanced"}),
                "val_macro_f1": row["macro_f1"],
                "evaluation_split": "validation",
            }
            for row in rows
        ]
    )
    combined = pd.concat([existing, entries], ignore_index=True).drop_duplicates(
        ["run_id", "variant"], keep="last"
    )
    combined.to_csv(log_path, index=False)


if __name__ == "__main__":
    publish(ROOT / "backend/models/ablations_preliminary_001")
    print(
        "Aggregate ablation report and model metrics updated; model artifact unchanged."
    )
